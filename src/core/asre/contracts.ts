/**
 * ==========================================================
 * LÉLU ASRE — TYPED CONTRACTS (Mission 5, WP01)
 *
 * The shapes every surface (server API, tools, Genesis UI, tests)
 * agrees on. Pure types plus two small pure functions; no Node, no DOM.
 *
 * EVIDENCE CLASSES — the words LÉLU uses when she talks about geometry:
 *
 *   OBSERVED      a captured observation directly supports it
 *   INFERRED      derived from observations by a measurement model
 *   INTERPOLATED  produced between two snapshots in time
 *   GENERATED     produced by a generative model or a shape prior with
 *                 no observation behind it (NRE name: SYNTHESIZED)
 *   UNKNOWN       nothing supports it either way (no evidence at all)
 *
 * The NRE stores a provenance bitmask per cell. `evidenceClass` maps it
 * to ONE class by strength (OBSERVED > INFERRED > GENERATED >
 * INTERPOLATED), so a cell that one source observed and another
 * generated is reported as OBSERVED — and never the other way round.
 * ==========================================================
 */

import { Provenance } from "./nre/types.ts";

export type EvidenceClass = "OBSERVED" | "INFERRED" | "INTERPOLATED" | "GENERATED" | "UNKNOWN";

export const EVIDENCE_CLASSES: readonly EvidenceClass[] = ["OBSERVED", "INFERRED", "GENERATED", "INTERPOLATED", "UNKNOWN"];

/** One provenance bitmask → the strongest evidence class it contains. */
export function evidenceClass(mask: number): EvidenceClass {
  if (mask & Provenance.OBSERVED) return "OBSERVED";
  if (mask & Provenance.INFERRED) return "INFERRED";
  if (mask & Provenance.SYNTHESIZED) return "GENERATED";
  if (mask & Provenance.INTERPOLATED) return "INTERPOLATED";
  return "UNKNOWN";
}

export type EvidenceBreakdown = Record<EvidenceClass, number>;

export function emptyBreakdown(): EvidenceBreakdown {
  return { OBSERVED: 0, INFERRED: 0, INTERPOLATED: 0, GENERATED: 0, UNKNOWN: 0 };
}

/**
 * A sentence that never upgrades evidence: what was seen, what was
 * inferred, what was made up, and what is unknown — with fractions.
 */
export function describeEvidence(b: EvidenceBreakdown, subject = "the geometry"): string {
  const total = b.OBSERVED + b.INFERRED + b.INTERPOLATED + b.GENERATED;
  if (!total) return `Nothing is known about ${subject}: there is no evidence for any of it.`;
  const pct = (n: number) => `${((n / total) * 100).toFixed(0)}%`;
  const parts = [`${pct(b.OBSERVED)} of ${subject} is OBSERVED (directly supported by an input view)`];
  if (b.INFERRED) parts.push(`${pct(b.INFERRED)} is INFERRED from the views by a measurement model (not seen)`);
  if (b.GENERATED) parts.push(`${pct(b.GENERATED)} is GENERATED by a model or shape prior with no observation behind it`);
  if (b.INTERPOLATED) parts.push(`${pct(b.INTERPOLATED)} is INTERPOLATED between snapshots`);
  const unknown = b.UNKNOWN ? `; ${b.UNKNOWN} region(s) have no evidence at all (UNKNOWN)` : "";
  return `${parts.join("; ")}${unknown}.`;
}

/* ------------------------------ job lifecycle ------------------------------ */

export type AsreJobKind = "reconstruct" | "observe";
export type AsreJobState = "queued" | "running" | "succeeded" | "failed" | "cancelled" | "interrupted";
export const TERMINAL_JOB_STATES: readonly AsreJobState[] = ["succeeded", "failed", "cancelled", "interrupted"];

export interface AsreJobStep {
  step: string;
  state: "running" | "done" | "failed" | "skipped" | "cancelled";
  ms?: number;
  note?: string;
}

/** Which engine produced a reconstruction. */
export type ReconstructionEngine = "silhouette" | "triposr";

export interface HypothesisSummary {
  id: string;
  label: string;
  /** How its depth/shape was obtained. */
  method: string;
  /** NRE class every non-observed cell of this hypothesis carries. */
  evidence: EvidenceClass;
  cells: number;
  /** Mean IoU with the other hypotheses (the agreement the ranking uses). */
  agreement: number;
  meshValid: boolean;
  triangles: number;
  glb: string | null;
  rank: number;
  selected: boolean;
}

export interface CoverageSummary {
  sides: Array<{ side: string; cells: number; unsupported: number; meanConfidence: number }>;
  overallUnsupported: number;
  requests: Array<{ view: string; reason: string; gain: number }>;
}

export interface ReconstructionResult {
  engine: ReconstructionEngine;
  /** Grid-level facts of the selected geometry. */
  grid: { cells: number; resolution: number; dims: [number, number, number]; boundary: number; interior: number; meanConfidence: number };
  evidence: EvidenceBreakdown;
  evidenceText: string;
  hypotheses: HypothesisSummary[];
  /** Pairwise IoU between hypotheses, keyed "a|b". */
  pairwiseIou: Record<string, number>;
  consensusCells: number;
  disagreementFraction: number;
  coverage: CoverageSummary;
  /** Asset-root-relative files. */
  files: { glb: string; lnre: string; preview?: string | null; hypotheses: Record<string, string> };
  mesh: { triangles: number; vertices: number; meshValid: boolean; problems: string[] };
  observations: Array<{ id: string; source: string; provenance: string; confidence: number; modality: string }>;
  /** Snapshot ids in the reconstruction's own history (each observation is one). */
  snapshots: Array<{ id: string; label: string; cells: number; hash: string; parentId: string | null }>;
  forgeJobId?: string | null;
}

export interface ObservationReport {
  view: string;
  duplicate: boolean;
  newCells: number;
  reinforcedCells: number;
  conflicts: number;
  carved: number;
  /** Silhouette evidence moved to the new nearest surface (hidden cells lose OBSERVED). */
  resurfaced: { stripped: number; attached: number };
  /** Conflicts the new view could not overrule: contradictions kept on record. */
  contradictions: number;
  preservedCells: number;
  unaffectedVerified: boolean;
  evidenceBefore: EvidenceBreakdown;
  evidenceAfter: EvidenceBreakdown;
  meanConfidenceBefore: number;
  meanConfidenceAfter: number;
  /** IoU of the geometry before and after this observation. */
  iouWithPrevious: number;
}

export interface AsreJobView {
  id: string;
  kind: AsreJobKind;
  state: AsreJobState;
  engine: ReconstructionEngine;
  /** For "observe": the reconstruction job this observation refines. */
  parentJobId: string | null;
  createdAt: number;
  startedAt: number | null;
  finishedAt: number | null;
  steps: AsreJobStep[];
  error: string | null;
  /** 0..1, derived from completed steps — never simulated. */
  progress: number;
  input: { images: Array<{ view: string; file: string; sha256: string }> };
  result: ReconstructionResult | null;
  observation: ObservationReport | null;
}
