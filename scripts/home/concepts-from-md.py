"""Regenerate src/app/scene/genesis/home/homeConceptNotes.ts from docs/missions/m15-home/CONCEPTS.md.

Each concept's research fields come from its entry; its catalog status comes from
the document's own totals table (so the two cannot disagree).
Run: python3 scripts/home/concepts-from-md.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MD = ROOT / "docs/missions/m15-home/CONCEPTS.md"
OUT = ROOT / "src/app/scene/genesis/home/homeConceptNotes.ts"
KEYS = ["Comp", "Pos", "Hier", "Nav", "Input", "M/D", "+", "−", "A11y", "Perf", "Cx", "Refs", "LÉLU"]


def clean(text: str) -> str:
    return text.replace("**", "").replace("*", "").replace("`", "").strip().rstrip(".")


def main() -> None:
    md = MD.read_text(encoding="utf-8")
    # Status per concept, from the totals table (| BUILT | 11 | #1, #2 … |).
    status = {}
    for label, nums in re.findall(r"^\| (BUILT|SUPPORTED[^|]*|PROPOSED|REJECT|BLOCKED) \| \d+ \| ([^|]+)\|", md, re.M):
        for n in re.findall(r"#(\d+)", nums):
            status[int(n)] = label.split()[0].split("/")[0].strip()
    entries, category = [], None
    pattern = r"(?:^|\. )(" + "|".join(re.escape(k) for k in KEYS) + r"): "
    for line in md.splitlines():
        m = re.match(r"^## \d+\. (.+)$", line)
        if m:
            category = m.group(1).strip()
            continue
        m = re.match(r"^\*\*(\d+)\. (.+?)\.\*\* (.*)$", line)
        if not m:
            continue
        n, name, body = int(m.group(1)), m.group(2), m.group(3)
        parts = re.split(pattern, body)
        fields = {parts[i]: parts[i + 1] for i in range(1, len(parts) - 1, 2)}
        missing = [k for k in KEYS if k not in fields]
        if missing:
            sys.exit(f"concept {n}: missing {missing}")
        refs = clean(fields["Refs"])
        entries.append({
            "n": n, "name": name, "category": category,
            "composition": clean(fields["Comp"]), "position": clean(fields["Pos"]), "hierarchy": clean(fields["Hier"]),
            "navigation": clean(fields["Nav"]), "input": clean(fields["Input"]), "devices": clean(fields["M/D"]),
            "strengths": clean(fields["+"]), "weaknesses": clean(fields["−"]), "a11y": clean(fields["A11y"]),
            "perf": clean(fields["Perf"]), "complexity": clean(fields["Cx"]), "refs": refs,
            "refKind": "original" if refs.startswith("Original") else "product",
            "catalogStatus": status.get(n, "SUPPORTED"), "catalogVerdict": clean(fields["LÉLU"]),
        })
    if [e["n"] for e in entries] != list(range(1, 61)):
        sys.exit("expected concepts 1..60")
    if len(status) != 60:
        sys.exit(f"totals table lists {len(status)} concepts, expected 60")
    header = '''/**
 * The sixty Home layout concepts — research notes, generated from
 * docs/missions/m15-home/CONCEPTS.md by scripts/home/concepts-from-md.py
 * (edit the document, then regenerate; do not edit this file by hand).
 * `catalogStatus` is the verdict the Mission 15 catalog recorded; the
 * working layout for every concept is in homeConcepts.ts.
 */
export interface ConceptNotes {
  n: number;
  name: string;
  category: string;
  composition: string;
  position: string;
  hierarchy: string;
  navigation: string;
  input: string;
  devices: string;
  strengths: string;
  weaknesses: string;
  a11y: string;
  perf: string;
  complexity: string;
  refs: string;
  refKind: "product" | "original";
  catalogStatus: "BUILT" | "SUPPORTED" | "PROPOSED" | "REJECT" | "BLOCKED";
  catalogVerdict: string;
}

export const CONCEPT_NOTES: ConceptNotes[] = '''
    OUT.write_text(header + json.dumps(entries, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    counts = {}
    for e in entries:
        counts[e["catalogStatus"]] = counts.get(e["catalogStatus"], 0) + 1
    print(f"wrote {OUT.relative_to(ROOT)}: {counts}")


if __name__ == "__main__":
    main()
