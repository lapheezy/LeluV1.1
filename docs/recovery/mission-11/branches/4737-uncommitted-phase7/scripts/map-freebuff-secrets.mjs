/**
 * LÉLU — MAP FREEBUFF SECRET NAMES TO LÉLU'S OWN NAMES
 *
 * Freebuff writes .env.local from the project's stored secrets using the
 * secret's DISPLAY name: `Supabase`, `Groq`, `Anthropic`, `Openrouter`.
 * LÉLU resolves its configuration through resolveEnv()/runtimeKeyBridge,
 * which only ever look under the documented names — SUPABASE_URL,
 * SUPABASE_PUBLISHABLE_KEY, GROQ_API_KEY, ANTHROPIC_API_KEY,
 * OPENROUTER_API_KEY and their VITE_ forms. Environment names are
 * case-sensitive and no alias anywhere maps a display name, so perfectly
 * good credentials sit in .env.local and every provider still reports
 * itself unconfigured. Measured: the model broker answered
 * /api/model/status {"anthropic":false,"groq":false,...} while the keys
 * were present in the process the whole time.
 *
 * This script copies each value across to the name LÉLU reads, into the
 * gitignored .env (which .env.local never overwrites, and which Vite and
 * plugins/loadEnvFiles.ts both load). It never prints, echoes or logs a
 * VALUE — only which names were mapped.
 *
 * Re-run it whenever the stored secrets change:
 *
 *     bun run scripts/map-freebuff-secrets.mjs
 *
 * then restart the dev server (the runtime key bridge publishes the
 * values into the page at server start, not per request).
 *
 * SUPABASE_URL is not a secret and is not stored by Freebuff, so it is
 * written from the project ref below — the project whose schema and data
 * every migration, test and verification script in this repository was
 * built against. Override with SUPABASE_URL=... in the shell if the
 * project ever moves.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";

/** The Supabase project this repository's schema and data live in. */
const SUPABASE_PROJECT_REF = "nrehsldbfxthspikaxvr";

/** Freebuff secret display name → the name LÉLU resolves. */
const MAP = [
  ["Supabase", "SUPABASE_PUBLISHABLE_KEY"],
  ["Anthropic", "ANTHROPIC_API_KEY"],
  ["Groq", "GROQ_API_KEY"],
  ["Openrouter", "OPENROUTER_API_KEY"],
];

function readEnvFile(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!match) continue;
    out[match[1]] = match[2].trim().replace(/^["']|["']$/g, "");
  }
  return out;
}

const source = readEnvFile(".env.local");
const existing = readEnvFile(".env");

/** Existing .env lines that this script does not manage, kept verbatim. */
const keptLines = existsSync(".env")
  ? readFileSync(".env", "utf8")
      .split("\n")
      .filter((line) => {
        const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=/);
        return !match || (match[1] !== "SUPABASE_URL" && !MAP.some(([, lelu]) => lelu === match[1]));
      })
  : [];

const mapped = [];
const missing = [];
const lines = [
  "# Generated by scripts/map-freebuff-secrets.mjs — do not edit values here.",
  "# Freebuff's .env.local uses secret DISPLAY names; LÉLU reads the names below.",
  `SUPABASE_URL=${process.env.SUPABASE_URL ?? existing.SUPABASE_URL ?? `https://${SUPABASE_PROJECT_REF}.supabase.co`}`,
];

for (const [freebuffName, leluName] of MAP) {
  const value = source[freebuffName] ?? existing[leluName];
  if (value) {
    lines.push(`${leluName}=${value}`);
    mapped.push(`${freebuffName} → ${leluName}`);
  } else {
    missing.push(`${leluName} (no value under "${freebuffName}" in .env.local)`);
  }
}

writeFileSync(".env", [...lines, ...keptLines.filter((l) => l.trim()), ""].join("\n"));

console.log("Mapped (names only, values never printed):");
for (const entry of mapped) console.log(`  ${entry}`);
if (missing.length > 0) {
  console.log("Not found — set these in Freebuff → Settings → Projects:");
  for (const entry of missing) console.log(`  ${entry}`);
}
console.log("Restart the dev server so the runtime key bridge publishes the new values.");
process.exit(missing.length > 0 ? 1 : 0);
